export const COURIER_FAILURE_STATUSES = [
  'PICKUP_FAILED',
  'DELIVERY_FAILED',
  'CUSTOMER_NOT_HOME',
  'CUSTOMER_CANCELLED',
  'WRONG_ADDRESS',
  'UNREACHABLE',
] as const;

export const COURIER_FAILURE_REASONS = [
  'CUSTOMER_NOT_HOME',
  'WRONG_ADDRESS',
  'CUSTOMER_CANCELLED',
  'UNREACHABLE',
  'OTHER',
] as const;

export function isValidCourierFailure(reason: unknown, notes: unknown) {
  return typeof reason === 'string' &&
    COURIER_FAILURE_REASONS.includes(reason as typeof COURIER_FAILURE_REASONS[number]) &&
    (reason !== 'OTHER' || (typeof notes === 'string' && notes.trim().length > 0));
}

